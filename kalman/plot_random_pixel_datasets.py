"""Generate plots for random pixel datasets with CCDC fit overlays."""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Iterable

import matplotlib.pyplot as plt
import pandas as pd

OBSERVED_COLUMN = "observed"
TIMESTAMP_COLUMN = "timestamp"
FIT_COLUMN = "ccdc_fit"
DATE_COLUMN = "date"
POINT_COLUMN = "point_id"
LONGITUDE_COLUMN = "longitude"
LATITUDE_COLUMN = "latitude"
SENSOR_COLUMN = "sensor"
BAND_COLUMN = "band"
SET_TYPE_COLUMN = "set_type"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Create per-point plots showing observed values and the CCDC fit "
            "from random pixel dataset CSV outputs."
        )
    )
    parser.add_argument(
        "csv_files",
        nargs="+",
        type=Path,
        help="One or more CSV files generated by generate_random_pixel_datasets.py",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help=(
            "Optional root directory for plots. Defaults to a 'plots' folder "
            "next to each input CSV."
        ),
    )
    parser.add_argument(
        "--dpi",
        type=int,
        default=150,
        help="Dots per inch for saved figures (default: 150).",
    )
    return parser.parse_args()


def ensure_output_directory(csv_path: Path, base_output: Path | None) -> Path:
    if base_output is not None:
        output_root = base_output
    else:
        output_root = csv_path.parent / "plots"
    dataset_name = csv_path.stem
    output_dir = output_root / dataset_name
    output_dir.mkdir(parents=True, exist_ok=True)
    return output_dir


def gather_metadata(group: pd.DataFrame) -> str:
    sensor = group[SENSOR_COLUMN].iloc[0] if SENSOR_COLUMN in group else "unknown_sensor"
    band = group[BAND_COLUMN].iloc[0] if BAND_COLUMN in group else "unknown_band"
    set_type = group[SET_TYPE_COLUMN].iloc[0] if SET_TYPE_COLUMN in group else "unknown_set"
    lon = group[LONGITUDE_COLUMN].iloc[0] if LONGITUDE_COLUMN in group else None
    lat = group[LATITUDE_COLUMN].iloc[0] if LATITUDE_COLUMN in group else None
    coords = f"lon={lon:.6f}, lat={lat:.6f}" if lon is not None and lat is not None else ""
    return f"{sensor} {band} ({set_type}) {coords}".strip()


def clean_group(group: pd.DataFrame) -> pd.DataFrame:
    cleaned = group.sort_values(TIMESTAMP_COLUMN).copy()
    cleaned[DATE_COLUMN] = pd.to_datetime(cleaned[TIMESTAMP_COLUMN], unit="ms")
    return cleaned


def plot_point_series(
    point_id: str,
    group: pd.DataFrame,
    output_dir: Path,
    dpi: int,
) -> None:
    cleaned = clean_group(group)
    observed = cleaned[cleaned[OBSERVED_COLUMN] != 0]
    if observed.empty and cleaned[FIT_COLUMN].isna().all():
        return

    fig, ax = plt.subplots(figsize=(10, 5))

    if not observed.empty:
        ax.scatter(
            observed[DATE_COLUMN],
            observed[OBSERVED_COLUMN],
            s=20,
            alpha=0.8,
            label="Observed",
            color="tab:blue",
        )

    if FIT_COLUMN in cleaned:
        ax.plot(
            cleaned[DATE_COLUMN],
            cleaned[FIT_COLUMN],
            color="tab:orange",
            linewidth=1.5,
            label="CCDC fit",
        )

    metadata = gather_metadata(cleaned)
    ax.set_title(f"Point {point_id} {metadata}".strip())
    ax.set_xlabel("Date")
    ax.set_ylabel("Value")
    ax.legend()
    fig.autofmt_xdate()

    output_path = output_dir / f"point_{point_id}.png"
    fig.savefig(output_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)


def process_csv(csv_path: Path, base_output: Path | None, dpi: int) -> None:
    data = pd.read_csv(csv_path)
    missing_columns = {
        column
        for column in (POINT_COLUMN, OBSERVED_COLUMN, TIMESTAMP_COLUMN, FIT_COLUMN)
        if column not in data.columns
    }
    if missing_columns:
        raise ValueError(
            f"CSV {csv_path} missing required columns: {sorted(missing_columns)}"
        )

    output_dir = ensure_output_directory(csv_path, base_output)

    for point_id, group in data.groupby(POINT_COLUMN):
        plot_point_series(str(point_id), group, output_dir, dpi)


def main() -> None:
    args = parse_args()
    for csv_file in args.csv_files:
        process_csv(csv_file, args.output_dir, args.dpi)


if __name__ == "__main__":
    main()
